import { chromium } from 'playwright';
const url = 'https://pie-pocket-elegant-juvenile.trycloudflare.com';
const browser = await chromium.launch({ args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 1280, height: 800 }});
const page = await ctx.newPage();
await page.goto(url, { waitUntil: 'networkidle' });
await page.waitForTimeout(1000);
await page.screenshot({ path: 'screenshots/final-start.png' });
console.log('pub start ok');
await page.click('#startBtn');
await page.waitForTimeout(800);
await page.screenshot({ path: 'screenshots/final-playing.png' });
console.log('pub playing ok');
await page.waitForTimeout(600);
await page.evaluate(()=>{ for(let i=0;i<3;i++) window.__neon.missStar(); });
await page.waitForTimeout(500);
await page.screenshot({ path: 'screenshots/final-gameover.png' });
console.log('pub gameover ok');
const mctx = await browser.newContext({ viewport: { width: 375, height: 812 }});
const mpage = await mctx.newPage();
await mpage.goto(url, { waitUntil: 'networkidle' });
await mpage.waitForTimeout(800);
await mpage.screenshot({ path: 'screenshots/final-mobile.png' });
console.log('pub mobile ok');
await browser.close();
